import os
from dotenv import load_dotenv
from openai import OpenAI

load_dotenv()
client = OpenAI()

def generate_parent_question() -> str:
    prompt = """
Ти — мама в київському батьківському Telegram-чаті (район Позняки / Осокорки).
Твоя мета: написати коротке, максимально природне запитання в чат до інших мам.

Тематика на вибір (випадкова):
1. Питання, де в районі Позняків/Осокорків можна наживо поміряти дитячий зимовий комбінезон (Reima, Lenne або якісний теплий суцільник), бо боїшся прогадати з розміром онлайн.
2. Дилема: що краще взяти на зріст 92-104 (Lenne чи Reima), і чи є десь поблизу шоурум або магазин із вибором.
3. Питання про теплі непромокаючі штани/напівкомбінезон або термобілизну для активної дитини.

Правила:
- Довжина: 1-2 короткі речення.
- Стиль: швидкий набір з телефону, звичайна жива мова (можна "мамочки, привіт", "хтось знає", "де глянути").
- Ніякої рекламності, ідеальної пунктуації чи канцелярщини.
- Поверни ТІЛЬКИ текст повідомлення без лапок і коментарів.
"""
    response = client.chat.completions.create(
        model="gpt-4o-mini",
        messages=[{"role": "user", "content": prompt}],
        temperature=0.85,
    )
    return response.choices[0].message.content.strip().strip('"')

if __name__ == "__main__":
    print("--- Sample Question ---")
    print(generate_parent_question())